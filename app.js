let currentLang = 'ua';

function setLanguage(lang) {
  if (!i18nData[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;

  document.querySelectorAll('.lang-pill-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18nData[lang][key]) {
      el.innerHTML = i18nData[lang][key];
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const mobileMenuBtn = document.getElementById('mobileMenuBtn');
  const navMenu = document.getElementById('navMenu');

  if (mobileMenuBtn && navMenu) {
    mobileMenuBtn.addEventListener('click', () => {
      navMenu.classList.toggle('mobile-open');
    });

    document.querySelectorAll('.nav-item-link').forEach(link => {
      link.addEventListener('click', () => {
        navMenu.classList.remove('mobile-open');
      });
    });
  }

  document.querySelectorAll('.lang-pill-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      setLanguage(btn.getAttribute('data-lang'));
    });
  });

  const dateInput = document.getElementById('modalDate');
  if (dateInput) {
    const tomorrow = new Date();
    tomorrow.setDate(tomorrow.getDate() + 1);
    dateInput.min = new Date().toISOString().split('T')[0];
    dateInput.value = tomorrow.toISOString().split('T')[0];
  }
});

function openLightbox(imgSrc, caption) {
  const modal = document.getElementById('lightboxModal');
  const img = document.getElementById('lightboxImg');
  if (modal && img) {
    img.src = imgSrc;
    modal.classList.add('active');
  }
}

function closeLightbox() {
  const modal = document.getElementById('lightboxModal');
  if (modal) modal.classList.remove('active');
}

function openBookingModal() {
  const modal = document.getElementById('bookingModal');
  if (modal) modal.classList.add('active');
}

function closeBookingModal() {
  const modal = document.getElementById('bookingModal');
  if (modal) modal.classList.remove('active');
}

function handleBookingSubmit(event) {
  event.preventDefault();

  const service = document.getElementById('modalServiceSelect').value;
  const date = document.getElementById('modalDate').value;
  const time = document.getElementById('modalTime').value;
  const name = document.getElementById('modalName').value;
  const phone = document.getElementById('modalPhone').value;

  const textMsg = `Hello Alena! ✂️\n\nI would like to book a haircut appointment:\n` +
                  `👤 Name: ${name}\n` +
                  `💇 Service: ${service}\n` +
                  `📅 Date & Time: ${date} at ${time}\n` +
                  `📱 Phone: ${phone}\n` +
                  `\nLocation: Kanton Bern, Schweiz 🇨🇭`;

  const waUrl = `https://wa.me/?text=${encodeURIComponent(textMsg)}`;
  closeBookingModal();
  window.open(waUrl, '_blank');
}
